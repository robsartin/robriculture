"""Package a single strategy into a submittable tarball.

The competition wants a `main.py` at the archive root, self-contained (no network
at eval). This script assembles: main.py (a thin shim) + the kaggisim package +
the strategies package, into dist/submission.tar.gz. Files land at
/kaggle_simulations/agent/ at runtime, so the shim's imports resolve there.

Usage (from repo root, venv active):
    python -m build.package greedy
    python -m build.package greedy -o dist/greedy.tar.gz

Then submit from your machine with your Kaggle CLI:
    kaggle competitions submit kaggriculture -f dist/greedy.tar.gz -m "greedy v1"

Sanity check: after building, this script re-imports the shim in a subprocess and
runs one short game to confirm the packaged agent loads and doesn't crash.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MAIN_SHIM = '''\
"""Auto-generated by build/package.py. Do not edit by hand."""
from kaggisim.state import parse
from strategies.{module} import STRATEGY

_agent = STRATEGY()


def agent(obs):
    try:
        return _agent.act(parse(obs))
    except Exception:
        # A crash during evaluation is an automatic loss; degrade to a safe PASS.
        return {{"farmer": ["PASS"], "hands": [], "market": []}}
'''


def build(strategy_name, out_path):
    sys.path.insert(0, REPO_ROOT)
    from strategies import REGISTRY
    if strategy_name not in REGISTRY:
        raise SystemExit(f"unknown strategy {strategy_name!r}; known: {sorted(REGISTRY)}")
    module = REGISTRY[strategy_name].split(".")[-1]

    with tempfile.TemporaryDirectory() as tmp:
        # Copy the two packages the agent needs at runtime.
        for pkg in ("kaggisim", "strategies"):
            shutil.copytree(
                os.path.join(REPO_ROOT, pkg),
                os.path.join(tmp, pkg),
                ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
            )
        # Write the generated entrypoint.
        with open(os.path.join(tmp, "main.py"), "w") as f:
            f.write(MAIN_SHIM.format(module=module))

        os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
        with tarfile.open(out_path, "w:gz") as tar:
            for name in sorted(os.listdir(tmp)):
                tar.add(os.path.join(tmp, name), arcname=name)

    print(f"built {out_path} (strategy: {strategy_name})")
    return out_path


def smoke_test(out_path):
    """Extract and run one short game to confirm the packaged agent works."""
    with tempfile.TemporaryDirectory() as tmp:
        with tarfile.open(out_path) as tar:
            tar.extractall(tmp)
        code = (
            "import sys; sys.path.insert(0, %r)\n"
            "from kaggle_environments import make\n"
            "import main\n"
            "env = make('kaggriculture', configuration={'episodeSteps': 120})\n"
            "env.run([main.agent, 'random'])\n"
            "print('smoke OK: reward', env.steps[-1][0].reward)\n" % tmp
        )
        r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True)
        print(r.stdout.strip() or r.stderr.strip())
        return r.returncode == 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="package a strategy for submission")
    ap.add_argument("strategy")
    ap.add_argument("-o", "--out", default=None, help="output tarball path")
    ap.add_argument("--no-smoke", action="store_true", help="skip the post-build smoke test")
    args = ap.parse_args(argv)

    out = args.out or os.path.join(REPO_ROOT, "dist", f"{args.strategy}.tar.gz")
    build(args.strategy, out)
    if not args.no_smoke:
        ok = smoke_test(out)
        if not ok:
            raise SystemExit("smoke test FAILED — do not submit this build")
    return 0


if __name__ == "__main__":
    sys.exit(main())
