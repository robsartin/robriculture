@pytest.fixture(autouse=True)
def _ladder_strict_off(monkeypatch):
    """Pin strict mode OFF for every test here — the ladder never runs strict.

    ``test_no_crash.py`` sets ROBRICULTURE_STRICT=1 process-globally to surface
    bugs in dev; we override it so these tests measure real ladder behaviour
    independent of test collection order.
    """
    monkeypatch.delenv("ROBRICULTURE_STRICT", raising=False)


@pytest.mark.parametrize("path", sorted(LIVE_AGENTS))
@pytest.mark.parametrize("obs_id,obs", MALFORMED, ids=[m[0] for m in MALFORMED])
def test_live_agent_never_raises_and_returns_legal_action(path, obs_id, obs):
    """No malformed observation may make a live champion agent raise; it must
    always return a structurally legal action (the safe PASS fallback)."""
    agent = LIVE_AGENTS[path]()
    action = agent(obs)  # must not raise
    assert _is_legal_action(action), f"{path}/{obs_id} returned illegal action: {action!r}"


@pytest.mark.parametrize("path", sorted(LIVE_AGENTS))
def test_malformed_input_degrades_to_the_safe_pass(path):
    """On garbage in, the wrapper degrades to the canonical safe-PASS no-op."""
    agent = LIVE_AGENTS[path]()
    assert agent(None) == {"farmer": ["PASS"], "hands": [], "market": []}


@pytest.mark.parametrize("path", sorted(LIVE_AGENTS))
def test_valid_observation_passes_through_untouched(path):
    """The fail-safe is transparent: a well-formed obs yields a real legal turn
    (the wrapper must not swallow good turns into a PASS)."""
    agent = LIVE_AGENTS[path]()
    action = agent(_valid_obs())
    assert _is_legal_action(action)
    # A fresh dawn board hires a crew, so this is a real turn, not the PASS no-op.
    assert action != {"farmer": ["PASS"], "hands": [], "market": []}


def test_champion_act_is_undefensive_by_design():
    """Guard the ADR-0006 architecture: the champion's own ``act`` is *not*
    self-defensive — malformed input raises there, and the single choke point is
    the wrapper. If this ever stops raising, the defensiveness has migrated onto
    the hot path (the design ADR-0006 explicitly rejected) and this test should
    be revisited deliberately."""
    champion = load(CHAMPION)()
    with pytest.raises(TypeError):  # None["player"] -> not subscriptable
        champion.act(None)


def test_both_live_paths_share_one_safe_pass_shape():
    """Drift guard: the harness wrapper and the submission shim must degrade to
    the *same* safe-PASS payload, so ADR-0006's 'identical local vs submission'
    guarantee can't silently diverge."""
    harness = _harness_agent()(None)
    submission = _submission_agent()(None)
    assert harness == submission == {"farmer": ["PASS"], "hands": [], "market": []}
