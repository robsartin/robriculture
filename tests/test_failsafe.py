"""Adversarial-observation fuzz guard for the champion (issue #51).

A crash during an episode is an automatic loss (ADR-0006), so the single
highest-value robustness property is: *the live agent never raises, no matter how
malformed the observation is, and always hands back a legal action.* This suite
proves that property directly by firing a battery of malformed / partial /
out-of-range / wrong-typed observations at the champion **through both live
execution paths**:

- the **harness path** — ``kaggisim.strategy.make_agent`` (what the tournament,
  the promotion gate and the no-crash guard all run), exercised here with strict
  mode **off**, i.e. exactly as the ladder runs it; and
- the **submission path** — the ``main.py`` shim generated by
  ``build.package.MAIN_SHIM`` (what actually runs on Kaggle), reconstructed here
  from the real template so we test the shipped guarantee, not a paraphrase.

Both paths wrap ``act(parse(obs))`` in ``try/except Exception`` and degrade any
error to a safe PASS, so the champion's own ``act`` is left un-defensive on
purpose (ADR-0006 keeps the single choke point in the wrapper). These tests
therefore assert the *wrapped agent's* contract, which is the one the ladder
depends on.

The strict-mode control matters: ``tests/test_no_crash.py`` sets
``ROBRICULTURE_STRICT=1`` at import to make bugs surface loudly in dev, and that
env var is process-global. The ladder runs with strict **off**, so every test
here pins strict off (``monkeypatch``) to measure the real ladder behaviour
regardless of test collection order.
"""

from __future__ import annotations

import pytest

from build.package import MAIN_SHIM
from kaggisim.strategy import make_agent
from strategies import load

CHAMPION = "ranch_hands"


# --- The two live agents under test ---------------------------------------

def _harness_agent():
    """The champion as the tournament / promotion gate runs it (make_agent)."""
    return make_agent(load(CHAMPION)())


def _submission_agent():
    """The champion as the *submission* runs it: the real generated main.py shim.

    We exec the actual ``MAIN_SHIM`` template (the same string build/package.py
    writes into the tarball) so this covers the shipped code path, not a copy.
    """
    namespace: dict = {}
    exec(MAIN_SHIM.format(module=CHAMPION), namespace)  # noqa: S102 - trusted template
    return namespace["agent"]


LIVE_AGENTS = {"harness": _harness_agent, "submission": _submission_agent}


def _is_legal_action(action) -> bool:
    """A structurally legal action dict: farmer/hands/market present and sane.

    The safe-PASS fallback ``{"farmer": ["PASS"], "hands": [], "market": []}`` and
    any real turn the champion emits both satisfy this; nothing malformed should.
    """
    if not isinstance(action, dict):
        return False
    farmer = action.get("farmer")
    hands = action.get("hands")
    market = action.get("market")
    return (
        isinstance(farmer, list)
        and len(farmer) >= 1
        and isinstance(hands, list)
        and isinstance(market, list)
        and len(market) <= 10
    )


# --- The malformed-observation battery ------------------------------------

def _grid(n=10):
    return [[None for _ in range(n)] for _ in range(n)]


